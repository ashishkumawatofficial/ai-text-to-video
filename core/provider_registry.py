# --- Registry Query Helpers ---

def get_provider_docs(provider_id: ProviderId) -> Optional[ProviderDocsEntry]:
    """Retrieve verified documentation and pricing link details for a given provider."""
    return PROVIDER_DOCS_REGISTRY.get(provider_id)


def get_all_provider_docs() -> List[ProviderDocsEntry]:
    """Retrieve full links bank for all supported providers."""
    return list(PROVIDER_DOCS_REGISTRY.values())


def get_model_profile(model_id: str) -> Optional[VideoModelProfile]:
    """Retrieve model metadata, character limits, and capability flags by model ID."""
    if model_id in MODEL_PROFILES_REGISTRY:
        return MODEL_PROFILES_REGISTRY[model_id]
    normalized = model_id.lower()
    if "flux" in normalized:
        if "max" in normalized or "3" in normalized:
            return MODEL_PROFILES_REGISTRY.get("flux-3-max")
        return MODEL_PROFILES_REGISTRY.get("flux-3")
    if "wan" in normalized:
        if "3" in normalized:
            return MODEL_PROFILES_REGISTRY.get("wan-3.0")
        if "2.2" in normalized:
            return MODEL_PROFILES_REGISTRY.get("wan-2.2")
        if "1.3b" in normalized:
            return MODEL_PROFILES_REGISTRY.get("wan-2.1-t2v-1.3b")
        if "i2v" in normalized:
            return MODEL_PROFILES_REGISTRY.get("wan-2.1-i2v-720p")
        return MODEL_PROFILES_REGISTRY.get("wan-2.1")
    if "grok" in normalized:
        return MODEL_PROFILES_REGISTRY.get("grok-video-1.5")
    if "veo-3.1" in normalized:
        return MODEL_PROFILES_REGISTRY.get("veo-3.1")
    if "veo" in normalized:
        return MODEL_PROFILES_REGISTRY.get("veo-3")
    if "kling-4" in normalized:
        return MODEL_PROFILES_REGISTRY.get("kling-v4.0")
    if "cogvideo" in normalized:
        return MODEL_PROFILES_REGISTRY.get("cogvideox-5b")
    if "hunyuan" in normalized:
        return MODEL_PROFILES_REGISTRY.get("hunyuan-video")
    if "kling-1.5" in normalized:
        return MODEL_PROFILES_REGISTRY.get("kling-v1.5")
    if "kling-1.0" in normalized:
        return MODEL_PROFILES_REGISTRY.get("kling-v1.0")
    if "kling-2.0" in normalized:
        return MODEL_PROFILES_REGISTRY.get("kling-v2.0")
    if "kling-2.5" in normalized:
        return MODEL_PROFILES_REGISTRY.get("kling-v2.5")
    if "kling-3.0" in normalized or "kling-3" in normalized:
        return MODEL_PROFILES_REGISTRY.get("kling-v3.0")
    if "seedance-1.5" in normalized:
        return MODEL_PROFILES_REGISTRY.get("seedance-1.5")
    if "seedance-2.5" in normalized:
        return MODEL_PROFILES_REGISTRY.get("seedance-2.5")
    if "seedance-2.0" in normalized:
        return MODEL_PROFILES_REGISTRY.get("seedance-2.0")
    if "runway" in normalized or "gen3" in normalized or "gen-3" in normalized:
        return MODEL_PROFILES_REGISTRY.get("runway-gen3-alpha")
    return None


def get_all_model_profiles() -> List[VideoModelProfile]:
    """Retrieve full catalog of supported video models."""
    return list(MODEL_PROFILES_REGISTRY.values())


def get_providers_for_model(model_id: str) -> List[ProviderId]:
    """List all configured providers that host the requested model."""
    profile = get_model_profile(model_id)
    return profile.supported_providers if profile else []
